export type OrderStatus =
  | "customizable"
  | "locked"
  | "skipped"
  | "processing"
  | "delivered";

export type MealCategory = "meals" | "breakfast" | "shakes" | "snacks" | "desserts";
export type DietaryTag = "GF" | "DF" | "NF" | "SF" | "H" | "SpF" | "V";

export interface PrepMethod { method: string; instructions: string; }

export interface Meal {
  id: string;
  name: string;
  planType: string;
  category: MealCategory;
  price: number;
  calories: number;
  protein: number;
  carbs: number;
  fat: number;
  dietaryTags: DietaryTag[];
  imageUrl: string;
  isNew?: boolean;
  description?: string;
  // Extended detail fields
  ingredients?: string[];
  allergens?: string[];
  saturatedFat?: number;
  polyUnsaturatedFat?: number;
  fiber?: number;
  sugar?: number;
  cholesterol?: number;
  sodium?: number;
  netCarbs?: number;
  prepMethods?: PrepMethod[];
  spiceLevel?: string[];
}

export interface OrderItem {
  id: string;
  meal: Meal;
  quantity: number;
  unitPrice: number;
  orderType?: 'one-time' | 'recurring';
}

export interface Order {
  id: string;
  deliveryDate: string;
  cutoffDate: string;
  billingDate: string;
  status: OrderStatus;
  items: OrderItem[];
  total: number;
}

